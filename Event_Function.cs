using System;
using System.Collections.Generic;
using System.Text;

namespace kysSharp
{
    partial class Event
    {
        //////////////////////////////////////////////////////////////////////
        /// <summary>
        /// 原对话指令（C# 版本）
        ///
        /// 对应 C++ 的：
        /// void Event::oldTalk(int talk_id, int head_id, int style)
        /// 实现角色头像、台词、对话框样式的切换。
        /// </summary>
        //////////////////////////////////////////////////////////////////////
        private void oldTalk(int talkId, int headId, int style)
        {
            ///////////////////////////////////////////////////////////////////////
            // 选择上方或下方对话框
            ///////////////////////////////////////////////////////////////////////
            Talk? talk;
            if (style % 2 == 0)
            {
                talk = talk_box_up_;
            }
            else
            {
                talk = talk_box_down_;
            }

            if (talk is null)
            {
                Console.WriteLine("[警告] 对话框对象未初始化。");
                return; // 安全退出
            }

            ///////////////////////////////////////////////////////////////////////
            // 设置对话内容
            ///////////////////////////////////////////////////////////////////////
            talk.setContent(talk_[talkId]);
            Console.WriteLine(talk_[talkId]);  // 控制台输出（调试用）

            ///////////////////////////////////////////////////////////////////////
            // 设置头像 ID（head_id）
            ///////////////////////////////////////////////////////////////////////
            talk.setHeadID(headId);

            // 若 style 为 2 或 3，则隐藏头像
            if (style == 2 || style == 3)
            {
                talk.setHeadID(-1);
            }

            ///////////////////////////////////////////////////////////////////////
            // 设置头像样式（左右朝向）
            ///////////////////////////////////////////////////////////////////////
            // 0/5 表示左侧头像
            if (style == 0 || style == 5)
            {
                talk.setHeadStyle(0);
            }

            // 4/1 表示右侧头像
            if (style == 4 || style == 1)
            {
                talk.setHeadStyle(1);
            }

            ///////////////////////////////////////////////////////////////////////
            // 执行对话
            ///////////////////////////////////////////////////////////////////////
            talk.run(false);
        }
    }
}
